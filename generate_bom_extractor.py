# ── Main ──────────────────────────────────────────────────────────────────────
def main():
    rows = enrich(parse_bom(BOM_RAW))

    total   = len(rows)
    parents = sum(1 for r in rows if r['IS_PARENT'])
    leaves  = total - parents
    max_lvl = max(r['LEVEL'] for r in rows)

    print(f"BOM parsed: {total} rows | {parents} parents | {leaves} leaves | max depth {max_lvl}")

    wb = openpyxl.Workbook()
    wb.remove(wb.active)   # remove default sheet

    build_full_bom(wb, rows)
    build_parents_only(wb, rows)
    build_instructions(wb)

    out_path = "Owner Inbox/On-Demand/CALLUM-001-BOM-ParentExtractor.xlsx"
    wb.save(out_path)
    print(f"Saved: {out_path}")
    print(f"  Sheet 1 — Full BOM:     {total} rows")
    print(f"  Sheet 2 — Parents Only: {parents} rows")
    print(f"  Sheet 3 — How to Use:   formulas + steps for new BOMs")


if __name__ == "__main__":
    main()
