def build_parents_only(wb, rows):
    ws = wb.create_sheet("Parents Only")
    ws.freeze_panes = "A3"

    ws.merge_cells("A1:G1")
    banner = ws["A1"]
    banner.value     = "PARENT ITEMS ONLY — items that have at least one child in this BOM"
    banner.font      = Font(name="Calibri", bold=True, color="FFFFFF", size=11)
    banner.fill      = hex_fill(C_PARENTS_H)
    banner.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[1].height = 18

    headers = ["ITEM NO.", "ERP SYSTEM #", "MANUFACTURER #", "DESCRIPTION", "QTY", "LEVEL", "CHILD COUNT"]
    for c, h in enumerate(headers, 1):
        apply_hdr(ws, 2, c, h, C_PARENTS_H, size=9)

    all_items = [r['ITEM_NO'] for r in rows]
    parents   = [r for r in rows if r['IS_PARENT']]

    for r_idx, r in enumerate(parents, 3):
        ino   = r['ITEM_NO']
        level = r['LEVEL']
        child_count = sum(1 for x in all_items if x.startswith(ino + '.') and
                          x[len(ino)+1:].count('.') == 0)   # direct children only

        apply_body(ws, r_idx, 1, ino,         C_PARENTS_R, bold=True, color="1F3864")
        apply_body(ws, r_idx, 2, r['ERP'],    C_PARENTS_R, size=9)
        apply_body(ws, r_idx, 3, r['MFR'],    C_PARENTS_R, size=9)
        apply_body(ws, r_idx, 4, r['DESC'],   C_PARENTS_R, bold=True)
        apply_body(ws, r_idx, 5, r['QTY'],    C_PARENTS_R, align="center")
        apply_body(ws, r_idx, 6, level,       C_PARENTS_R, align="center")
        apply_body(ws, r_idx, 7, child_count, C_PARENTS_R, align="center", bold=True, color="375623")

    col_widths(ws, [14, 22, 22, 50, 6, 7, 12])
    ws.sheet_view.showGridLines = False
    return ws


