def parse_bom(raw_text):
    """Parse tab-separated BOM text into list of dicts."""
    lines = raw_text.strip().split('\n')
    rows = []
    for line in lines[1:]:  # skip header
        if not line.strip():
            continue
        parts = line.split('\t')
        item_no = parts[0].strip() if len(parts) > 0 else ''
        erp     = parts[1].strip() if len(parts) > 1 else ''
        mfr     = parts[2].strip() if len(parts) > 2 else ''
        desc    = parts[3].strip() if len(parts) > 3 else ''
        qty     = parts[4].strip() if len(parts) > 4 else ''
        if item_no:
            rows.append({
                'ITEM_NO': item_no,
                'ERP':     erp,
                'MFR':     mfr,
                'DESC':    desc,
                'QTY':     qty,
            })
    return rows


def enrich(rows):
    """Add Level and Is_Parent to each row."""
    all_items = set(r['ITEM_NO'] for r in rows)
    result = []
    for r in rows:
        ino   = r['ITEM_NO']
        level = ino.count('.') + 1
        is_p  = any(other.startswith(ino + '.') for other in all_items)
        result.append({**r, 'LEVEL': level, 'IS_PARENT': is_p})
    return result


def apply_hdr(ws, row, col, value, bg, fg="FFFFFF", bold=True, size=10, align="left"):
    cell = ws.cell(row=row, column=col, value=value)
    cell.font      = Font(name="Calibri", bold=bold, color=fg, size=size)
    cell.fill      = hex_fill(bg)
    cell.alignment = Alignment(horizontal=align, vertical="center")
    cell.border    = thin_border()
    return cell


def apply_body(ws, row, col, value, bg, bold=False, size=10, color="000000", align="left", wrap=False):
    cell = ws.cell(row=row, column=col, value=value)
    cell.font      = Font(name="Calibri", bold=bold, color=color, size=size)
    cell.fill      = hex_fill(bg)
    cell.alignment = Alignment(horizontal=align, vertical="center", wrap_text=wrap)
    cell.border    = thin_border()
    return cell


def col_widths(ws, widths):
    for col_idx, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(col_idx)].width = w


# ── Sheet 1: Full BOM ────────────────────────────────────────────────────────
def build_full_bom(wb, rows):
    ws = wb.create_sheet("Full BOM")
    ws.freeze_panes = "A3"
    ws.row_dimensions[1].height = 18
    ws.row_dimensions[2].height = 14

    # Banner
    ws.merge_cells("A1:H1")
    banner = ws["A1"]
    banner.value     = "FULL BILL OF MATERIALS — all items with parent/leaf flag and level"
    banner.font      = Font(name="Calibri", bold=True, color="FFFFFF", size=11)
    banner.fill      = hex_fill(C_HEADER)
    banner.alignment = Alignment(horizontal="center", vertical="center")

    # Column headers
    headers = ["ITEM NO.", "ERP SYSTEM #", "MANUFACTURER #", "DESCRIPTION", "QTY", "LEVEL", "IS PARENT", "INDENT"]
    bg_hdrs = [C_HEADER]*8
    for c, (h, bg) in enumerate(zip(headers, bg_hdrs), 1):
        apply_hdr(ws, 2, c, h, bg, size=9)

    # Data rows
    for r_idx, r in enumerate(rows, 3):
        ino      = r['ITEM_NO']
        is_par   = r['IS_PARENT']
        level    = r['LEVEL']
        bg       = C_PARENT if is_par else C_LEAF
        lvl_col  = C_LEVEL[min(level-1, len(C_LEVEL)-1)]

        # Indent string (visual)
        indent_str = "  " * (level - 1) + ("▶ " if is_par else "• ")

        apply_body(ws, r_idx, 1, ino,                         bg,      bold=is_par, color="1F3864" if is_par else "000000")
        apply_body(ws, r_idx, 2, r['ERP'],                    bg,      size=9)
        apply_body(ws, r_idx, 3, r['MFR'],                    bg,      size=9)
        apply_body(ws, r_idx, 4, r['DESC'],                   bg,      bold=is_par)
        apply_body(ws, r_idx, 5, r['QTY'],                    bg,      align="center")
        apply_body(ws, r_idx, 6, level,                       lvl_col, align="center", bold=True)
        apply_body(ws, r_idx, 7, "PARENT" if is_par else "",  bg,      bold=is_par,
                   color="375623" if is_par else "999999", align="center")
        apply_body(ws, r_idx, 8, indent_str + r['DESC'],      bg,      size=9)

    col_widths(ws, [14, 22, 22, 45, 6, 7, 9, 55])
    ws.sheet_view.showGridLines = False
    return ws


